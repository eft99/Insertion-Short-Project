class CLIPDataset(torch.utils.data.Dataset):
    def __init__(self, dataset, processor):
        self.dataset = dataset
        self.processor = processor

    def __len__(self):
        return len(self.dataset)

    def __getitem__(self, idx):
        item = self.dataset[idx]

        # Görüntüyü yükle ve işle
        image = Image.open(item["image"]).convert("RGB")

        # Processor'ı uygula
        inputs = self.processor(
            text=[item["text"]],
            images=image,
            return_tensors="pt",
            padding='max_length',  # Maksimum uzunluğa kadar padding yap
            truncation=True,
            max_length=77,         # CLIP'in maksimum token uzunluğu
        )

        # Batch boyutunu kaldır
        for key in inputs.keys():
            inputs[key] = inputs[key].squeeze()

        return inputs

def collate_fn(batch):
    batch_size = len(batch)

    # Maksimum uzunluğu bul
    max_len = max(item['input_ids'].size(0) for item in batch)

    # Tensörleri hazırla
    input_ids = torch.zeros(batch_size, max_len, dtype=torch.long)
    attention_mask = torch.zeros(batch_size, max_len, dtype=torch.long)
    pixel_values = torch.stack([item['pixel_values'] for item in batch])

    # Her örneği pad'le
    for i, item in enumerate(batch):
        input_len = item['input_ids'].size(0)
        input_ids[i, :input_len] = item['input_ids']
        attention_mask[i, :input_len] = item['attention_mask']

    return {
        'input_ids': input_ids,
        'attention_mask': attention_mask,
        'pixel_values': pixel_values,
    }

