def validate_data(data):
    """Veri setini doğrula ve eksik/hatalı öğeleri raporla"""
    valid_data = []
    for idx, item in enumerate(data):
        is_valid = True
        if "resim_dosyasi" not in item:
            print(f"Hata: {idx}. öğede 'resim_dosyasi' anahtarı eksik")
            is_valid = False
        if "urun_ismi" not in item or "aciklama" not in item:
            print(f"Hata: {idx}. öğede 'urun_ismi' veya 'aciklama' anahtarı eksik")
            is_valid = False
        if is_valid:
            if not os.path.exists(item["resim_dosyasi"]):
                print(f"Uyarı: {item['resim_dosyasi']} dosyası bulunamadı")
                is_valid = False
        if is_valid:
            valid_data.append(item)
    return valid_data

